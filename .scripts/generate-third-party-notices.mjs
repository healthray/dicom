/**
 * Regenerates THIRD-PARTY-NOTICES.md from the installed production dependency
 * tree.
 *
 *   node .scripts/generate-third-party-notices.mjs
 *
 * Run it whenever production dependencies change. MIT (and most permissive
 * licences) require preserving copyright and permission notices when
 * redistributing, which a bundled web app does on every page load.
 *
 * `pnpm licenses list --prod` is the source of truth: it walks the actual
 * lockfile-resolved tree rather than the top-level manifests, so transitive
 * dependencies are included.
 *
 * Compound licence strings are reported verbatim. Where a package offers a
 * choice ("MIT OR GPL-3.0-or-later"), the elected licence is recorded in
 * ELECTIONS below so the choice is documented rather than implied.
 */
import { exec } from 'child_process';
import { promisify } from 'util';
import fs from 'fs/promises';

const execAsync = promisify(exec);

/**
 * Licences this project elects where a package offers a choice. Anything
 * matching / OR / that is not listed here is flagged in the output as needing a
 * decision, rather than being silently assumed.
 */
const ELECTIONS = {
  'jszip': { from: '(MIT OR GPL-3.0-or-later)', elected: 'MIT' },
};

/** Licence families that need legal review before shipping commercially. */
const REVIEW_REQUIRED = /AGPL|SSPL|BUSL|Commons Clause|(^|[^L])GPL-/i;

async function main() {
  // A fixed command string with no interpolated input. `exec` (rather than
  // execFile) because pnpm is a .cmd shim on Windows, which Node refuses to
  // spawn without a shell.
  const { stdout } = await execAsync('pnpm licenses list --prod --json', {
    maxBuffer: 64 * 1024 * 1024,
  });

  const byLicense = JSON.parse(stdout);
  const buckets = Object.entries(byLicense).sort((a, b) => b[1].length - a[1].length);
  const total = buckets.reduce((sum, [, pkgs]) => sum + pkgs.length, 0);

  const needsReview = buckets.filter(([license]) => REVIEW_REQUIRED.test(license));
  const unknown = byLicense['Unknown'] ?? [];

  const lines = [];
  lines.push('# Third-party notices');
  lines.push('');
  lines.push(
    'This product bundles third-party software. The packages below are present in the',
    'production dependency tree and their licences are reproduced by reference.',
    ''
  );
  lines.push(
    '> Generated by `.scripts/generate-third-party-notices.mjs`. Do not edit by hand —',
    '> regenerate after any production dependency change.',
    ''
  );
  lines.push(`Production packages: **${total}** across **${buckets.length}** licence declarations.`);
  lines.push('');

  if (needsReview.length) {
    lines.push('## ⚠ Requires legal review');
    lines.push('');
    for (const [license, pkgs] of needsReview) {
      const elected = pkgs
        .map(p => ELECTIONS[p.name])
        .find(e => e && e.from === license);
      const note = elected ? ` — elected **${elected.elected}**` : ' — **no election recorded**';
      lines.push(`- \`${license}\`${note}: ${pkgs.map(p => p.name).join(', ')}`);
    }
    lines.push('');
  }

  if (unknown.length) {
    lines.push('## Unresolved licences');
    lines.push('');
    lines.push('These declare no licence in their manifest and must be confirmed manually:');
    lines.push('');
    for (const p of unknown) {
      lines.push(`- \`${p.name}\`${p.versions ? ` (${p.versions.join(', ')})` : ''}${p.homepage ? ` — ${p.homepage}` : ''}`);
    }
    lines.push('');
  }

  lines.push('## Packages by licence');
  lines.push('');
  for (const [license, pkgs] of buckets) {
    if (license === 'Unknown') {
      continue;
    }
    lines.push(`### ${license} (${pkgs.length})`);
    lines.push('');
    lines.push(pkgs.map(p => p.name).sort().join(', '));
    lines.push('');
  }

  await fs.writeFile('THIRD-PARTY-NOTICES.md', lines.join('\n'));
  console.log(`Wrote THIRD-PARTY-NOTICES.md — ${total} packages, ${buckets.length} licences.`);
  if (needsReview.length) {
    console.warn(`Review required for: ${needsReview.map(([l]) => l).join(' | ')}`);
  }
  if (unknown.length) {
    console.warn(`Unresolved licences: ${unknown.map(p => p.name).join(', ')}`);
  }
}

main().catch(err => {
  console.error('Failed to generate third-party notices:', err);
  process.exit(1);
});
